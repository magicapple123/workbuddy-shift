/// 记录一条应用内提示；前端所有 toast 都会同步写一份，失败不影响提示本身。
#[tauri::command]
pub async fn record_notification(
    level: String,
    title: String,
    description: Option<String>,
) -> Result<Value, String> {
    // 与 webui POST /api/notifications/record 同形（前端类型也按对象声明）。
    notifications::record(&level, &title, description.as_deref())?;
    Ok(json!({ "recorded": true }))
}

/// 读取最近的通知（新的在前，最多 100 条）。
#[tauri::command]
pub async fn list_notifications() -> Result<Value, String> {
    Ok(json!({ "items": notifications::list()? }))
}

/// 清空通知存档。
#[tauri::command]
pub async fn clear_notifications() -> Result<Value, String> {
    // 与 webui POST /api/notifications/clear 同形。
    notifications::clear()?;
    Ok(json!({ "cleared": true }))
}

/// POST /api/save-text-file —— 把文本（CSV）写到用户选定的路径。
///
/// 只允许 `.csv`、≤16 MiB；校验在 core，两个宿主共用同一套错误文案。
#[tauri::command(rename_all = "camelCase")]
pub async fn save_text_file(path: String, content: String) -> Result<serde_json::Value, String> {
    tauri::async_runtime::spawn_blocking(move || {
        wb_shift_core::modules::export_file::save_text_file(&path, &content)
    })
    .await
    .map_err(|error| error.to_string())?
}
